"""
generate_report.py

Builds the typeset thesis report.

The prose lives in report/thesis_report.tex, which is a static document.
Every NUMBER in that document is injected from the experimental output
by this script, as LaTeX macros written to report/generated/numbers.tex,
and every table is generated from the result CSVs into
report/generated/tables/. Nothing numeric is typed into the prose by
hand, so the report cannot drift away from the experiment: re-running
the pipeline and recompiling updates the document automatically, and a
macro whose experiment has not been run fails loudly at compile time
rather than silently printing a stale figure.

Usage:
    python generate_report.py            # write macros + tables, compile PDF
    python generate_report.py --no-pdf   # write macros + tables only
"""

