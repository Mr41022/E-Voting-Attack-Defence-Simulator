def compile_pdf() -> str | None:
    tex_name = "thesis_report.tex"
    if shutil.which("pdflatex") is None:
        print("[report] pdflatex not found -- skipping PDF compilation.")
        return None
    for run in range(3):          # 3 passes: toc, refs, page numbers
        proc = subprocess.run(
            ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex_name],
            cwd=REPORT_DIR, capture_output=True, text=True)
        if proc.returncode != 0:
            tail = "\n".join(proc.stdout.strip().splitlines()[-40:])
            print(f"[report] pdflatex failed on pass {run + 1}:\n{tail}")
            return None
    pdf_path = os.path.join(REPORT_DIR, "thesis_report.pdf")
    return pdf_path if os.path.exists(pdf_path) else None


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the typeset thesis report")
    parser.add_argument("--no-pdf", action="store_true", help="write macros/tables only")
    args = parser.parse_args()

    os.makedirs(GEN_DIR, exist_ok=True)
    os.makedirs(TABLE_DIR, exist_ok=True)

    with open(os.path.join(config.JSON_DIR, "summary.json")) as fh:
        summary = json.load(fh)

    def load_json(name):
        path = os.path.join(config.JSON_DIR, name)
        return json.load(open(path)) if os.path.exists(path) else None

    def load_csv(name):
        path = os.path.join(config.CSV_DIR, name)
        return pd.read_csv(path) if os.path.exists(path) else None

    election = load_json("election_outcome_summary.json")
    thresholds = load_json("threshold_analysis.json")
    thr_df = load_csv("table_11_scenario_thresholds.csv")
    vector_df = load_csv("table_12_vector_optima.csv")
    coalition_df = load_csv("table_13_coalition.csv")
    bribery_df = load_csv("bribery_results.csv")

    missing = [n for n, v in (("election_outcome_summary.json", election),
                              ("threshold_analysis.json", thresholds)) if v is None]
    if missing:
        print(f"[report] WARNING: missing {', '.join(missing)}; "
              f"run the corresponding CLI first. Macros for those sections will be absent "
              f"and the LaTeX compile will fail loudly rather than print stale numbers.")

    macros = build_macros(summary, election, thresholds, thr_df, coalition_df, bribery_df, vector_df)
    sybil_df = load_csv("sybil_results.csv")
    ballot_df = load_csv("ballot_stuffing_results.csv")
    if sybil_df is not None and ballot_df is not None:
        build_worked_example_macros(macros, bribery_df, sybil_df, ballot_df)
    macros.write(os.path.join(GEN_DIR, "numbers.tex"))
    build_tables(summary, thr_df, vector_df, coalition_df)

    print(f"[report] Wrote {len(macros.items)} macros to {GEN_DIR}/numbers.tex")
    print(f"[report] Wrote generated tables to {TABLE_DIR}/")

    if not args.no_pdf:
        pdf = compile_pdf()
        if pdf:
            size_kb = os.path.getsize(pdf) / 1024
            print(f"[report] Built {pdf} ({size_kb:,.0f} KB)")
        else:
            sys.exit(1)


if __name__ == "__main__":
    main()
