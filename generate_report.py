def build_tables(summary: dict, thr_df: pd.DataFrame | None,
                 vector_df: pd.DataFrame | None, coalition_df: pd.DataFrame | None) -> None:
    os.makedirs(TABLE_DIR, exist_ok=True)

    # --- parameter ranges
    ranges = pd.DataFrame([
        {"Symbol": sym, "Meaning": meaning, "Range": rng}
        for sym, meaning, rng in [
            ("$N$", "Electorate size", "200 -- 5{,}000"),
            ("$m$", "Manipulation threshold", "2\\% -- 25\\% of $N$"),
            ("$B$", "Attacker budget", "1{,}000 -- 200{,}000"),
            ("$R$", "Bribe reward per voter", "10 -- 500"),
            ("$P$", "Penalty if a bribed voter is caught", "10 -- 2{,}000"),
            ("$q$", "Bribery detection probability (baseline)", "0.02 -- 0.25"),
            ("$q$", "Bribery detection probability (protected)", "baseline $+$ 0.15 -- 0.60"),
            ("$S$", "Attempted forged identities", "10 -- 1{,}000"),
            ("$q_s$", "Registration acceptance (baseline)", "0.40 -- 0.95"),
            ("$p_d$", "Sybil detection (baseline)", "0.02 -- 0.30"),
            ("$A$", "Attempted fraudulent ballots", "10 -- 1{,}000"),
            ("$q_b$", "Ballot acceptance (baseline)", "0.30 -- 0.90"),
            ("$p_b$", "Ballot detection (baseline)", "0.02 -- 0.30"),
            # The four protected-configuration parameters for Sybil and
            # ballot stuffing were missing from this table while the
            # bribery equivalent was shown, so the only table claiming to
            # document config.py did not document the protected arm of two
            # of the three vectors.
            ("$q_s$", "Registration acceptance (protected)",
             "baseline $\\times\\,(1 -$ 0.30 -- 0.80$)$"),
            ("$p_d$", "Sybil detection (protected)", "baseline $+$ 0.20 -- 0.70"),
            ("$q_b$", "Ballot acceptance (protected)",
             "baseline $\\times\\,(1 -$ 0.30 -- 0.80$)$"),
            ("$p_b$", "Ballot detection (protected)", "baseline $+$ 0.20 -- 0.70"),
        ]])
    write_table(os.path.join(TABLE_DIR, "parameter_ranges.tex"), ranges,
                "Randomised parameter ranges. Every trial draws one value per symbol "
                "uniformly from these ranges; the protected configuration modifies only the "
                "acceptance and detection probabilities, never $N$, $m$, $B$, $R$, $P$, $S$ or $A$.",
                "tab:parameters", column_format="llr",
                note="Source: \\texttt{config.py::PARAM\\_RANGES}. Currency-like quantities are "
                     "unitless in the model; only ratios such as $B/R$ affect the results.")

    # --- headline comparison
    rows = []
    for attack in ("bribery", "sybil", "ballot_stuffing"):
        ce = summary["countermeasure_effectiveness"][attack]
        cv = summary["chernoff_validation"][attack]
        mc = summary["monte_carlo_validation"][attack]
        rows.append({
            "Attack": _nice(attack),
            "Baseline": ce["mean_baseline"],
            "Protected": ce["mean_protected"],
            "Absolute red.": ce["absolute_reduction"],
            "Relative red. (\\%)": 100 * ce["relative_reduction"],
            "95\\% CI": f"[{ce['bootstrap_ci_low']:.3f}, {ce['bootstrap_ci_high']:.3f}]",
            "MC error": f"{mc['mean_absolute_error']:.1e}",
            "Bound holds (\\%)": cv["pct_bound_holds"],
        })
    write_table(os.path.join(TABLE_DIR, "headline.tex"), pd.DataFrame(rows),
                "Headline experimental results across 2{,}500 paired randomised trials per vector.",
                "tab:headline", column_format="lrrrrccr",
                note="Confidence intervals are bootstrap intervals on the mean paired reduction "
                     "(10{,}000 resamples). ``Bound holds'' is the percentage of trials with a "
                     "mathematically valid Chernoff region in which the bound was not violated.")

    # --- thresholds
    if thr_df is not None:
        base = thr_df[thr_df.system_type == "baseline"].copy()
        # All SEVEN solvers, not five. R* (T1) and T_min (T3) were solved
        # and exported to CSV but omitted from this table, while the text
        # described it as collecting every threshold.
        tbl = pd.DataFrame({
            "Scenario": base["scenario_id"],
            "$N$": base["N"].map("{:,}".format),
            "$m$": base["m"].map("{:,}".format),
            "$R^*$": base["R_star"].map(lambda v: f"{v:,.0f}" if pd.notna(v) else "---"),
            "$q_v^*$": base["q_voter_indifference"].round(3),
            "$T_{\\min}$": base["T_min_for_even_odds"].map(
                lambda v: f"{v:,.0f}" if pd.notna(v) else "---"),
            "$q_d^*$": base["q_defender_critical"].round(3),
            "$B^*$": base["B_star"].map(lambda v: f"{v:,.0f}" if pd.notna(v) else "---"),
            "$T^*$": base["T_star"].map("{:,}".format),
            "$m_\\alpha$": base["m_reachable"].map(lambda v: f"{v:,.0f}" if pd.notna(v) else "---"),
            "$m_\\varepsilon$": base["m_certified"].map(
                lambda v: f"{v:,.0f}" if pd.notna(v) else "---"),
            "$P(X \\geq m)$": base["exact_p_flip"].round(3),
        })
        write_table(os.path.join(TABLE_DIR, "thresholds.tex"), tbl,
                    "Critical thresholds for the five benchmark scenarios under the baseline "
                    "configuration.", "tab:thresholds", column_format="l" + "r" * 11,
                    note="$R^*$ minimum bribe a rational voter accepts (T1); "
                         "$q_v^*$ voter-indifference detection (T2); $T_{\\min}$ attempts for "
                         "even odds (T3); $q_d^*$ critical detection "
                         "at which attacking stops paying (T5); $B^*$ break-even budget (T4); "
                         "$T^*$ utility-maximising attempts; $m_\\alpha$ margin beaten at even "
                         "odds (T7); $m_\\varepsilon$ Chernoff-certified safe margin at "
                         "$\\varepsilon = 10^{-3}$ (T6). A dash means the threshold does not "
                         "exist in the searched domain.")

    # --- coalition
    if coalition_df is not None:
        base = coalition_df[coalition_df.system_type == "baseline"].copy()
        tbl = pd.DataFrame({
            "Scenario": base["scenario_id"],
            "Bribery": base["share_bribery"].map("{:.0%}".format).str.replace("%", "\\%"),
            "Sybil": base["share_sybil"].map("{:.0%}".format).str.replace("%", "\\%"),
            "Ballot": base["share_ballot_stuffing"].map("{:.0%}".format).str.replace("%", "\\%"),
            "$\\mu_{\\mathrm{total}}$": base["mu_total"].map("{:,.0f}".format),
            "Coalition $P$": base["coalition_exact_p"].round(3),
            "Best pure": base["best_pure_vector"].map(lambda s: _nice(s)),
            "Pure $P$": base["best_pure_exact_p"].round(3),
            "Gain": base["coalition_gain_p"].round(3),
        })
        write_table(os.path.join(TABLE_DIR, "coalition.tex"), tbl,
                    "Optimal multi-vector budget allocation per scenario (baseline "
                    "configuration).", "tab:coalition", column_format="lrrrrrlrr",
                    note="Shares are the fractions of one budget allocated to each vector. "
                         "Coalition success probability is computed exactly, by convolving the "
                         "three binomial distributions rather than approximating their sum.")

    # --- vector capacity
    if vector_df is not None:
        base = vector_df[vector_df.system_type == "baseline"].copy()
        base["capacity"] = base["n_feasible"] * base["p_survive"] / base["m"]
        order = ["bribery", "sybil", "ballot_stuffing"]
        pivot = (base.pivot(index="scenario_id", columns="vector", values="capacity")
                 .reindex(columns=order)          # attack order, not alphabetical
                 .reset_index())
        pivot.columns = ["Scenario"] + [_nice(c) for c in order]
        pivot["Combined"] = pivot.iloc[:, 1:].sum(axis=1)
        write_table(os.path.join(TABLE_DIR, "capacity.tex"), pivot,
                    "Capacity of each vector at full effort, as a multiple of the manipulation "
                    "threshold $m$ (baseline configuration).", "tab:capacity",
                    column_format="lrrrr", float_format="%.2f",
                    note="Values are EXPECTED surviving votes over the threshold, so a value "
                         "below 1.00 means the mean falls short --- not that the threshold is "
                         "unreachable. Success remains possible on an upward fluctuation, though "
                         "its probability collapses quickly: at a ratio of 0.97 the exact "
                         "$P(X \\geq m)$ is still 0.42 for bribery in S1, while by a ratio of "
                         "0.74 it is numerically zero. Every entry here falls below 1.00; the "
                         "budget-feasible optimal coalition clears it in four of the five "
                         "scenarios (\\tabref{tab:coalition}).")


