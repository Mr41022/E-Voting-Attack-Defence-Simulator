def tex_escape(text: str) -> str:
    for old, new in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                     ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                     ("}", r"\}"), ("~", r"\textasciitilde{}"),
                     ("^", r"\textasciicircum{}")):
        text = text.replace(old, new)
    return text


class Macros:
    """Collects `\newcommand` definitions, rejecting duplicates and
    non-alphabetic names (LaTeX command names cannot contain digits)."""

    _DIGIT_WORDS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
                    "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}

    def __init__(self):
        self.items: dict[str, str] = {}

    @classmethod
    def _clean(cls, name: str) -> str:
        out = []
        for ch in name:
            if ch.isdigit():
                out.append(cls._DIGIT_WORDS[ch])
            elif ch.isalpha():
                out.append(ch)
        return "".join(out)

    def add(self, name: str, value) -> str:
        key = self._clean(name)
        if key in self.items and self.items[key] != str(value):
            raise ValueError(f"macro {key} defined twice with different values")
        self.items[key] = str(value)
        return key

    def num(self, name: str, value: float, decimals: int = 3) -> str:
        return self.add(name, f"{value:.{decimals}f}")

    def pct(self, name: str, value: float, decimals: int = 1) -> str:
        """value given as a fraction; rendered as a percentage number."""
        return self.add(name, f"{100.0 * value:.{decimals}f}")

    def integer(self, name: str, value: float) -> str:
        return self.add(name, f"{int(round(value)):,}")

    def write(self, path: str) -> None:
        lines = ["% Generated by generate_report.py -- do not edit by hand.",
                 "% Every value here is read from results/ output.", ""]
        for key in sorted(self.items):
            lines.append(f"\\newcommand{{\\{key}}}{{{self.items[key]}}}")
        with open(path, "w") as fh:
            fh.write("\n".join(lines) + "\n")


def write_table(path: str, df: pd.DataFrame, caption: str, label: str,
                column_format: str | None = None, note: str | None = None,
                float_format: str = "%.3f", landscape: bool = False,
                fit: bool = True, escape: bool = False) -> None:
    """Write one booktabs table as a standalone .tex fragment.

    `fit` wraps the tabular in a \resizebox so a wide table shrinks to the
    text block instead of overflowing into the margin. Scaling down is
    preferable to a smaller declared font here because it preserves the
    booktabs rule weights proportionally.
    """
    # escape=False by default: these tables carry deliberate LaTeX in their
    # cells (maths for symbols, thousands separators). Any value derived from
    # data passes through _nice(), which removes the underscores that would
    # otherwise need escaping.
    body = df.to_latex(index=False, escape=escape, float_format=float_format,
                       column_format=column_format or ("l" + "r" * (len(df.columns) - 1)),
                       longtable=False)
    if fit:
        body = ("\\resizebox{\\textwidth}{!}{%\n" + body.rstrip() + "%\n}")
    env = "table*" if landscape else "table"
    lines = [f"\\begin{{{env}}}[htbp]", "\\centering",
             f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             "\\small", body.rstrip()]
    if note:
        lines.append(f"\\vspace{{2pt}}\n{{\\footnotesize\\textit{{Note.}} {note}}}")
    lines.append(f"\\end{{{env}}}")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def _nice(name: str) -> str:
    return name.replace("_", " ").replace("ballot stuffing", "ballot stuffing").title()


