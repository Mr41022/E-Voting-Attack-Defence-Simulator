def build_macros(summary: dict, election: dict | None, thresholds: dict | None,
                 thr_df: pd.DataFrame | None, coalition_df: pd.DataFrame | None,
                 bribery_df: pd.DataFrame,
                 vector_df: pd.DataFrame | None = None) -> Macros:
    m = Macros()

    m.integer("TotalTrials", summary["total_trials"])
    m.add("Seed", summary["seed"])
    m.integer("MonteCarloTrials", summary["mc_trials_per_scenario"])
    m.num("RuntimeSeconds", summary["elapsed_seconds"], 1)
    # Counts that describe the project itself. Injected rather than typed,
    # for the same reason every other number is: a hand-written count goes
    # stale the moment a test or figure is added, and nothing catches it.
    m.integer("TestCount", _count_test_functions())
    m.integer("FigureCount", _count_figures())
    m.integer("ElectorateMin", bribery_df["N"].min())
    m.integer("ElectorateMax", bribery_df["N"].max())

    for attack in ("bribery", "sybil", "ballot_stuffing"):
        tag = "".join(part.capitalize() for part in attack.split("_"))
        ce = summary["countermeasure_effectiveness"][attack]
        m.num(f"{tag}Baseline", ce["mean_baseline"])
        m.num(f"{tag}Protected", ce["mean_protected"])
        m.num(f"{tag}AbsReduction", ce["absolute_reduction"])
        m.pct(f"{tag}RelReduction", ce["relative_reduction"])
        m.num(f"{tag}CILow", ce["bootstrap_ci_low"])
        m.num(f"{tag}CIHigh", ce["bootstrap_ci_high"])
        mc = summary["monte_carlo_validation"][attack]
        m.add(f"{tag}MCError", f"{mc['mean_absolute_error']:.2e}".replace("e-0", "e-"))
        m.num(f"{tag}MCMaxError", mc["max_absolute_error"], 4)
        cv = summary["chernoff_validation"][attack]
        m.integer(f"{tag}ChernoffValid", cv["n_valid"])
        m.num(f"{tag}ChernoffHolds", cv["pct_bound_holds"], 1)
        m.num(f"{tag}ChernoffGap", cv["mean_conservativeness"], 4)
        bs = summary["baseline_statistics"][attack]
        m.num(f"{tag}BaselineMedian", bs["median"], 4)
        m.num(f"{tag}BaselineStd", bs["std"])

    # Acceptance-gate-only means for the two two-gate vectors. These are
    # NOT the headline measure -- they ignore detection -- but the report
    # quotes them explicitly when explaining why the per-vector and the
    # aggregate tables differ, so they are injected like everything else
    # rather than typed. Read straight from the per-attack results so the
    # prose cannot drift from the tables.
    for attack, path in (("sybil", "sybil_results.csv"),
                         ("ballot_stuffing", "ballot_stuffing_results.csv")):
        tag = "".join(part.capitalize() for part in attack.split("_"))
        full = os.path.join(config.CSV_DIR, path)
        if not os.path.exists(full):
            continue
        df = pd.read_csv(full)
        col = "exact_probability_accepted_ge_m"
        if col not in df.columns:
            continue
        for system in ("baseline", "protected"):
            label = "Baseline" if system == "baseline" else "Protected"
            m.num(f"{tag}Accepted{label}", df[df.system_type == system][col].mean())

    # Exact success probability at FULL structural effort for two cells the
    # findings quote when explaining that the capacity ratio is a mean
    # rather than a ceiling. Computed here, not typed, so the sentence
    # cannot drift from the data it describes.
    if vector_df is not None:
        from scipy.stats import binom as _binom
        _b = vector_df[vector_df.system_type == "baseline"]
        for macro, sid, vec in (("SOneBriberyPFull", "S1", "bribery"),
                                ("SThreeBallotPFull", "S3", "ballot_stuffing")):
            r = _b[(_b.scenario_id == sid) & (_b.vector == vec)]
            if len(r) == 1:
                r = r.iloc[0]
                m.num(macro, float(_binom.sf(int(r["m"]) - 1, int(r["n_feasible"]),
                                             float(r["p_survive"]))), 3)

    # Coalition baseline: the best SINGLE-vector success probabilities, so
    # the discussion can say what single-vector analysis did find rather
    # than asserting it found nothing.
    if coalition_df is not None:
        _c = coalition_df[coalition_df.system_type == "baseline"]["best_pure_exact_p"]
        # Restricted to scenarios where SOME single vector was viable at
        # all: including the scenario where nothing works would make the
        # range read 0.000-0.423 and say nothing.
        _cv = _c[_c > 0]
        if len(_cv):
            m.num("BestPureMin", float(_cv.min()), 3)
            m.num("BestPureMax", float(_cv.max()), 3)
            m.integer("BestPureViableCount", int(len(_cv)))

    # Share of trials falling on the LOWER tail (m <= mu), per vector, and
    # the certificate's mean interval width. Both were previously typed
    # into the prose as rounded ranges.
    _cert = summary.get("chernoff_certificate_validation", {})
    _shares, _widths = [], {}
    for attack in ("bribery", "sybil", "ballot_stuffing"):
        tag = "".join(part.capitalize() for part in attack.split("_"))
        c = _cert.get(attack, {})
        if c.get("n_rows"):
            _shares.append(100.0 * float(c["n_lower_bounded"]) / float(c["n_rows"]))
        if "mean_interval_width" in c:
            _widths[tag] = float(c["mean_interval_width"])
    for tag, w in _widths.items():
        m.num(f"{tag}IntervalWidth", w, 3)
    if _shares:
        m.num("LowerTailShareMin", min(_shares), 1)
        m.num("LowerTailShareMax", max(_shares), 1)

    conv = summary.get("monte_carlo_convergence")
    if conv:
        m.integer("ConvergenceSettles", conv["settles_within_tolerance_from"])
        m.num("ConvergenceTolerance", conv["tolerance"], 2)
        m.integer("ConvergenceMinSize", min(conv["sample_sizes"]))
        m.integer("ConvergenceMaxSize", max(conv["sample_sizes"]))
        m.num("ConvergenceFinalError", conv["final_absolute_error"], 4)

    # Electorate-size sweep endpoints, per vector. The findings chapter
    # quotes these because the direction of the effect is NOT the same
    # for all three, and an aggregate statement would be false for Sybil.
    _sw = os.path.join(config.CSV_DIR, "electorate_size_sweep.csv")
    if os.path.exists(_sw):
        sw = pd.read_csv(_sw).sort_values("N")
        for col, tag in (("bribery_baseline", "Bribery"),
                         ("sybil_baseline", "Sybil"),
                         ("ballot_baseline", "Ballot")):
            if col in sw.columns and len(sw):
                m.num(f"Scale{tag}Small", float(sw[col].iloc[0]), 3)
                m.num(f"Scale{tag}Large", float(sw[col].iloc[-1]), 3)

    m.add("MostResilient", tex_escape(
        str(summary.get("most_resilient_attack_under_test_conditions", "n/a")).replace("_", " ")))

    tm = summary.get("threshold_m_statistics", {})
    if tm:
        for key, macro in (("mean", "ThresholdMean"), ("min", "ThresholdMin"),
                           ("max", "ThresholdMax"), ("median", "ThresholdMedian")):
            if key in tm:
                m.integer(macro, tm[key])

    if election:
        m.integer("ElectionTrials", election["total_trials"])
        for attack, rates in election["flip_rates"].items():
            tag = "".join(part.capitalize() for part in attack.split("_"))
            m.pct(f"Flip{tag}Baseline", rates["baseline_flip_rate"])
            m.pct(f"Flip{tag}Protected", rates["protected_flip_rate"])
            m.pct(f"Flip{tag}RelReduction", rates["relative_reduction"])
        m.add("ChainIntegrityHeld",
              "never violated" if election["chain_integrity_never_violated"]
              else "VIOLATED -- see log")

    if thresholds and thr_df is not None:
        cm = thresholds["cost_model"]
        m.pct("IdentityCostRatio", cm["identity_cost_ratio"], 0)
        m.pct("BallotCostRatio", cm["ballot_cost_ratio"], 0)
        m.pct("SybilCeilingPct", cm["sybil_ceiling_fraction"], 0)
        m.pct("BallotCeilingPct", cm["ballot_ceiling_fraction"], 0)
        m.add("CertificationEpsilon", f"10^{{-{abs(int(round(_log10(cm['certification_epsilon']))))}}}")
        m.num("ProtectedQ", thresholds["voter_gate"]["protected_q"], 2)
        m.integer("GateOpenBaseline", thresholds["voter_gate"]["n_scenarios_gate_open_baseline"])
        m.integer("GateOpenProtected", thresholds["voter_gate"]["n_scenarios_gate_open_protected"])

        base = thr_df[thr_df.system_type == "baseline"]
        # S5's critical detection is exactly zero because that attack never
        # pays at any detection level; quoting it as the low end of a range
        # would misdescribe the finding, so the range covers only scenarios
        # where detection is the binding constraint.
        binding = base[base["q_defender_critical"] > 0]
        m.num("CriticalDetectionMin", binding["q_defender_critical"].min(), 3)
        m.integer("CriticalDetectionBindingCount", len(binding))
        m.num("CriticalDetectionMax", base["q_defender_critical"].max(), 3)
        m.num("VoterIndifferenceMin", base["q_voter_indifference"].min(), 3)
        m.num("VoterIndifferenceMax", base["q_voter_indifference"].max(), 3)
        for row in base.itertuples():
            tag = row.scenario_id
            m.integer(f"{tag}N", row.N)
            m.integer(f"{tag}M", row.m)
            m.integer(f"{tag}Budget", row.B)
            m.num(f"{tag}QCritical", row.q_defender_critical, 3)
            m.num(f"{tag}QVoter", row.q_voter_indifference, 3)
            m.num(f"{tag}ExactFlip", row.exact_p_flip, 3)
            m.integer(f"{tag}TStar", row.T_star)
            if pd.notna(row.B_star):
                m.integer(f"{tag}BStar", row.B_star)
            if pd.notna(row.m_reachable):
                m.integer(f"{tag}MReachable", row.m_reachable)
            if pd.notna(row.m_certified):
                m.integer(f"{tag}MCertified", row.m_certified)

        detection_ratio = thresholds["voter_gate"]["protected_q"] / max(
            float(base["q_defender_critical"].max()), 1e-9)
        m.num("ProtectionHeadroom", detection_ratio, 1)

    if thresholds and coalition_df is not None:
        coal = thresholds["coalition"]
        base_coal = coalition_df[coalition_df.system_type == "baseline"]
        m.num("CoalitionMeanBaseline", coal["mean_baseline_exact_p"])
        m.num("CoalitionMeanProtected", coal["mean_protected_exact_p"])
        m.num("CoalitionMeanGain", coal["mean_gain_over_best_pure_baseline"])
        m.integer("CoalitionBetterCount", coal["n_scenarios_coalition_strictly_better"])
        m.integer("CoalitionScenarioCount", len(base_coal))
        m.num("BestPureMeanBaseline", base_coal["best_pure_exact_p"].mean())
        if "sensitivity" in thresholds:
            m.integer("SensitivityConfigs", thresholds["sensitivity"]["n_configurations"])
            m.num("SensitivityAtLeastAsGood",
                  thresholds["sensitivity"]["pct_coalition_at_least_as_good"], 0)
            m.num("SensitivityStrictlyBetter",
                  thresholds["sensitivity"]["pct_coalition_strictly_better"], 0)

    return m


def _count_test_functions() -> int:
    """Number of test functions on disk, counted the way pytest collects."""
    import glob
    import re as _re
    total = 0
    for path in glob.glob("tests/test_*.py"):
        total += len(_re.findall(r"^def (test_\w+)", open(path).read(), flags=_re.M))
    return total


def _count_figures() -> int:
    """Number of generated figures, counted from the vector PDFs."""
    import glob
    return len(glob.glob("results/plots/fig_*.pdf"))


def _log10(x: float) -> float:
    import math
    return math.log10(x)


WORKED_TRIAL_ID = 79
"""Trial traced step by step in the report's experiment walkthrough.

Chosen because this single trial exhibits all three of the behaviours the
model is built to distinguish: the bribery voter-rationality gate closing
between the two arms; a Sybil attack whose expected surviving count sits
far above the threshold in one arm and far below it in the other; and a
ballot-stuffing attack that is structurally infeasible because fewer
ballots are attempted than the threshold requires. It is an ordinary
trial drawn by the sampler, not a constructed illustration.
"""


def build_worked_example_macros(m: Macros, bribery_df: pd.DataFrame,
                                sybil_df: pd.DataFrame,
                                ballot_df: pd.DataFrame) -> None:
    """Inject the numbers for the traced trial, so the walkthrough in the
    report quotes the experiment rather than a retyped copy of it."""
    def row(df, system):
        sub = df[(df.trial_id == WORKED_TRIAL_ID) & (df.system_type == system)]
        return sub.iloc[0] if len(sub) else None

    b_base, b_prot = row(bribery_df, "baseline"), row(bribery_df, "protected")
    if b_base is None:
        return

    m.integer("WEtrial", WORKED_TRIAL_ID)
    m.integer("WEN", b_base["N"])
    m.integer("WEm", b_base["m"])
    m.integer("WEB", b_base["B"])
    m.num("WER", b_base["R"], 2)
    m.num("WEP", b_base["P"], 2)
    m.integer("WET", b_base["T"])

    for tag, r in (("Base", b_base), ("Prot", b_prot)):
        m.num(f"WEq{tag}", r["q"], 3)
        m.num(f"WEUv{tag}", r["Uv"], 2)
        m.add(f"WEdecision{tag}", str(r["voter_decision"]))
        m.num(f"WEpsurvive{tag}", r["p_success"], 3)
        m.num(f"WEmu{tag}", r["expected_successful_votes"], 1)
        m.num(f"WEexact{tag}", r["exact_probability"], 3)
        m.num(f"WEmc{tag}", r["monte_carlo_probability"], 3)
        cher = r["chernoff_bound"]
        m.add(f"WEchernoff{tag}", "not applicable" if pd.isna(cher) else f"{cher:.3f}")

    s_base, s_prot = row(sybil_df, "baseline"), row(sybil_df, "protected")
    if s_base is not None:
        m.integer("WES", s_base["S"])
        for tag, r in (("Base", s_base), ("Prot", s_prot)):
            m.num(f"WEqs{tag}", r["qs"], 3)
            m.num(f"WEpd{tag}", r["pd"], 3)
            m.num(f"WEsybilmu{tag}", r["expected_surviving"], 1)
            m.num(f"WEsybilP{tag}", r["surviving_ge_m_exact_probability"], 3)

    z_base, z_prot = row(ballot_df, "baseline"), row(ballot_df, "protected")
    if z_base is not None:
        m.integer("WEA", z_base["A"])
        for tag, r in (("Base", z_base), ("Prot", z_prot)):
            m.num(f"WEqb{tag}", r["qb"], 3)
            m.num(f"WEpb{tag}", r["pb"], 3)
            m.num(f"WEballotmu{tag}", r["expected_surviving"], 1)
            m.num(f"WEballotP{tag}", r["surviving_ge_m_exact_probability"], 3)


